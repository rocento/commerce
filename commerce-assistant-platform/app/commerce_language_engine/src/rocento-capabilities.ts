export function compatibleCase(c:CorpusCase, codes:ReadonlySet<string>):boolean {
 return (!c.intent||codes.has(c.intent))&&(!c.context?.previousIntent||codes.has(c.context.previousIntent));
}

/** Remove unsupported actions and every intent-bearing dependent definition. */
export function rocentoDictionary(source:Dictionary):Dictionary {
 const d=structuredClone(source);
 d.intents=d.intents.filter(i=>rocentoIntentCodes.has(i.code));
 const codes=new Set(d.intents.map(i=>i.code));
 for(const i of d.intents)i.previousIntents=i.previousIntents.filter(code=>codes.has(code));
 d.transitions=d.transitions.filter(t=>codes.has(t.intent)&&codes.has(t.previousIntent));
 d.conflicts=d.conflicts.filter(pair=>pair.every(code=>codes.has(code)));
 d.patterns=d.patterns.filter(p=>codes.has(p.intent));
 d.actionFrames=d.actionFrames?.filter(f=>codes.has(f.intent));
 d.corpus=d.corpus.filter(c=>compatibleCase(c,codes));
 if(d.semanticModel){
  const m=d.semanticModel;
  m.intentSlots=m.intentSlots.filter(s=>codes.has(s.intent));
  m.clarificationPolicies=m.clarificationPolicies.filter(p=>codes.has(p.intent));
  const frames=new Set(d.actionFrames?.map(f=>f.code));
  m.actionFrameSlots=m.actionFrameSlots.filter(s=>frames.has(s.frame));
  m.confidenceCalibrations=[]; // Old calibration no longer describes this candidate set.
 }
 return d;
}
