"""Deterministic Swift/Kotlin models and bundled schemas from the backend contract.

Only the schema constructs explicitly handled here are supported. New schema
keywords fail generation instead of silently weakening native validation.
"""
import argparse, hashlib, json, re
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
SOURCE=ROOT/'commerce-api/rocento-api/crates/domain-mobile/contract/v1'
MOBILE=ROOT/'commerce-mobile-apps'
SCHEMA=json.loads((SOURCE/'schema.json').read_text())
ALLOWED={'$schema','$id','title','type','additionalProperties','properties','required','$defs','$ref','oneOf','enum','pattern','items','minItems','maxItems','uniqueItems','minimum','maximum','minLength','maxLength','minProperties','maxProperties','propertyNames'}
def check(s):
    assert not set(s)-ALLOWED, set(s)-ALLOWED
    for k,v in s.items():
        if k in ('properties','$defs'):
            for x in v.values():check(x)
        elif k in ('items','additionalProperties','propertyNames') and isinstance(v,dict):check(v)
        elif k=='oneOf':
            for x in v:check(x)
check(SCHEMA)

def pascal(s):return s[0].upper()+s[1:]
structs={};enums={};unions={}
def resolve(s):return SCHEMA['$defs'][s['$ref'].split('/')[-1]] if '$ref' in s else s
def typename(s,name):
    if '$ref' in s:
        n=s['$ref'].split('/')[-1];return typename(SCHEMA['$defs'][n],pascal(n))
    if 'oneOf' in s:
        if name not in unions:
            unions[name]=[]
            for branch in s['oneOf']:
                b=resolve(branch); tag=b['properties']['type']['enum'][0];n=pascal(tag) if name=='Section' else 'Action'+pascal(tag)
                unions[name].append((tag,n));structs[n]=(b,name)
                for k,v in b['properties'].items():
                    if k!='type':typename(v,n+pascal(k))
        return name
    if s.get('enum'):
        if len(s['enum'])==1:return 'String'
        enums[name]=s['enum'];return name
    t=s['type']
    if t=='object':
        if 'properties' not in s:
            return 'Map<'+typename(s['additionalProperties'],name+'Value')+'>'
        if name not in structs:
            structs[name]=(s,None)
            for k,v in s['properties'].items():typename(v,name+pascal(k))
        return name
    if t=='array':return 'List<'+typename(s['items'],name+'Item')+'>'
    return {'string':'String','integer':'Int','boolean':'Bool'}[t]
typename(SCHEMA,'MobileConfig')
def swift(t):
    if t.startswith('List<'):return '['+swift(t[5:-1])+']'
    if t.startswith('Map<'):return '[String: '+swift(t[4:-1])+']'
    return t

def kotlin(t):return t.replace('Bool','Boolean').replace('Map<','Map<String, ')
fingerprint=hashlib.sha256((SOURCE/'schema.json').read_bytes()).hexdigest()
sw=['// Generated by commerce-mobile-apps/tools/generate_contract.py. Do not edit.','// Schema SHA-256: '+fingerprint,'import Foundation\n']
kt=['// Generated by commerce-mobile-apps/tools/generate_contract.py. Do not edit.','// Schema SHA-256: '+fingerprint,'package com.rocento.mobile.contract','import kotlinx.serialization.*','import kotlinx.serialization.json.JsonClassDiscriminator\n']
for name,values in enums.items():
    sw += [f'public enum {name}: String, Codable, Sendable, CaseIterable {{',*[f'    case `{v}` = "{v}"' for v in values],'}\n']
    kt += [f'@Serializable enum class {name} {{',',\n'.join(f'    @SerialName("{v}") {v}' for v in values),'}\n']
for name,(s,parent) in structs.items():
    fields=[(k,typename(v,name+pascal(k)),k not in s.get('required',[])) for k,v in s['properties'].items() if not (parent and k=='type')]
    sw += [f'public struct {name}: Codable, Sendable {{',*[f'    public let {k}: {swift(t)}'+('?' if opt else '') for k,t,opt in fields],'}\n']
    kt += ['@Serializable'+(f' @SerialName("{s["properties"]["type"]["enum"][0]}")' if parent else ''),f'data class {name}(', ',\n'.join(f'    val {k}: {kotlin(t)}'+('? = null' if opt else '') for k,t,opt in fields),')'+(f' : {parent}' if parent else ''),'']
for name,options in unions.items():
    sw += [f'public enum {name}: Codable, Sendable {{',*[f'    case {tag}({typ})' for tag,typ in options],'    private enum CodingKeys: String, CodingKey { case type }','    public init(from decoder: Decoder) throws {','        let box = try decoder.container(keyedBy: CodingKeys.self)','        switch try box.decode(String.self, forKey: .type) {',*[f'        case "{tag}": self = .{tag}(try {typ}(from: decoder))' for tag,typ in options],'        default: throw DecodingError.dataCorruptedError(forKey: .type, in: box, debugDescription: "Unknown registered type")','        }','    }','    public func encode(to encoder: Encoder) throws {','        var box = encoder.container(keyedBy: CodingKeys.self)','        switch self {',*[f'        case .{tag}(let value): try box.encode("{tag}", forKey: .type); try value.encode(to: encoder)' for tag,typ in options],'        }','    }','}\n']
    kt += ['@OptIn(ExperimentalSerializationApi::class)','@Serializable @JsonClassDiscriminator("type")',f'sealed interface {name}\n']
outputs={MOBILE/'ios/RocentoCore/Sources/RocentoCore/Contract.generated.swift':'\n'.join(sw)+'\n',MOBILE/'android/core/src/main/java/com/rocento/mobile/contract/Contract.generated.kt':'\n'.join(kt)+'\n'}
outputs[ROOT/'commerce-web/packages/api-client/src/mobile-contract.json']=(SOURCE/'schema.json').read_text()
for platform in ['ios/RocentoCore/Sources/RocentoCore/Resources','android/core/src/main/assets']:
    base=MOBILE/platform
    outputs[base/'schema.json']=(SOURCE/'schema.json').read_text()
    for f in (SOURCE/'fixtures').glob('*.json'):outputs[base/f.name]=f.read_text()
    for folder in ['shared/catalog','shared/production']:
        for f in (MOBILE/folder).glob('*.json'):outputs[base/f.name]=f.read_text()
for platform in ['ios/RocentoCore/Tests/RocentoCoreTests/Resources','android/core/src/test/resources','android/app/src/androidTest/assets']:
    for f in (MOBILE/'shared/testing').glob('*.json'):outputs[MOBILE/platform/f.name]=f.read_text()
for platform in ['ios/RocentoCore/Sources/RocentoCore/Resources','android/core/src/main/assets']:
    for asset in (MOBILE/'shared/production/branding').glob('*.asset'):
        target=MOBILE/platform/asset.name
        if '--check' in __import__('sys').argv:
            assert target.exists() and target.read_bytes()==asset.read_bytes(), f'Stale branding: {target}'
        else:
            target.parent.mkdir(parents=True,exist_ok=True);target.write_bytes(asset.read_bytes())
args=argparse.ArgumentParser();args.add_argument('--check',action='store_true');opts=args.parse_args()
for p,s in outputs.items():
    if opts.check:
        assert p.exists() and p.read_text()==s, f'Stale generated output: {p}'
    else:p.parent.mkdir(parents=True,exist_ok=True);p.write_text(s)
print(f'{"Checked" if opts.check else "Generated"} {len(outputs)} native contract/resources files')
