"""Bundle the pinned delivery map for Android, React Native, and App Studio."""
from pathlib import Path
import json
root=Path(__file__).resolve().parents[2]
source=root/'commerce-mobile-apps/shared/maps'
css=(source/'vendor/leaflet.css').read_text()+'\n'+(source/'map.css').read_text()
js=(source/'vendor/leaflet.js').read_text()+'\n'+(source/'location-map.js').read_text()
body='<div id="map" role="application" aria-label="Delivery map"></div><div id="status" role="status"></div>'
head='<!doctype html><html><head><meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1"><meta charset="utf-8">'
inline=head+'<style>'+css+'</style></head><body>'+body+'<script>'+js.replace('</script','<\\/script')+'</script></body></html>'
android=root/'commerce-mobile-apps/android/app/src/main/assets/location-map.html';android.parent.mkdir(parents=True,exist_ok=True);android.write_text(inline)
(root/'commerce-mobile-apps/react-native/src/ui/locationMapDocument.ts').write_text('// Generated by commerce-mobile-apps/tools/generate_location_map.py\nexport const locationMapDocument = '+json.dumps(inline)+';\n')
web=root/'commerce-web/apps/mobile-studio/public/maps';web.mkdir(parents=True,exist_ok=True)
(web/'map.html').write_text(head+'<link rel="stylesheet" href="map.css"></head><body>'+body+'<script src="map.js"></script></body></html>')
(web/'map.css').write_text(css);(web/'map.js').write_text(js);(web/'LICENSE').write_text((source/'vendor/LICENSE').read_text())

for target in (root/"commerce-mobile-apps/react-native/src/ui/addressLookup.ts", root/"commerce-web/apps/mobile-studio/src/addressLookup.ts"):
    target.write_text("// Generated by commerce-mobile-apps/tools/generate_location_map.py\n"+(source/"addressLookup.ts").read_text())
