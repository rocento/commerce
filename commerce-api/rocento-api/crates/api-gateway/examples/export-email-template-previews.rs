//! Export the actual built-in templates for visual review, without a database or provider.
//! cargo run -p api-gateway --example export-email-template-previews -- /tmp/email-previews
use api_gateway::email_templates::render_builtin_notification;
use infra_auth::Notification;
use serde_json::json;
use std::{error::Error, fs, path::PathBuf};

fn main() -> Result<(), Box<dyn Error>> {
    let output = std::env::args_os()
        .nth(1)
        .map(PathBuf::from)
        .ok_or("Usage: export-email-template-previews <output-directory>")?;
    fs::create_dir_all(&output)?;
    let mut samples = Vec::new();
    for (key, link) in [
        (
            "verify",
            "https://store.example.test/verify?token=preview-only-confirmation",
        ),
        (
            "reset",
            "https://store.example.test/reset-password?token=preview-only-reset",
        ),
        (
            "order",
            "Order #1042 confirmed. Total: 125.50 EGP. Payment: Cash on Delivery.",
        ),
        (
            "shipment",
            "Order #1042 has shipped. Tracking reference: SAMPLE-1042",
        ),
    ] {
        let notification = Notification {
            identifier: "preview@example.test".into(),
            purpose: key.into(),
            code: "preview-only".into(),
            mobile: false,
            link: link.into(),
        };
        let rendered = render_builtin_notification(&notification)?;
        fs::write(output.join(format!("{key}.html")), &rendered.html)?;
        fs::write(output.join(format!("{key}.txt")), &rendered.text)?;
        fs::write(
            output.join(format!("{key}.json")),
            serde_json::to_vec_pretty(&rendered)?,
        )?;
        samples.push(json!({"key": key, "subject": rendered.subject,
            "html":format!("{key}.html"), "text":format!("{key}.txt"), "json":format!("{key}.json")}));
    }
    fs::write(
        output.join("manifest.json"),
        serde_json::to_vec_pretty(&json!({
            "description":"Built-in transactional email previews generated by the production renderer; all data is synthetic.",
            "samples":samples
        }))?,
    )?;
    println!("Exported four email previews to {}", output.display());
    Ok(())
}
