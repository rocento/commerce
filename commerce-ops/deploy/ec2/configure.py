def validate_domain(value):
    if (len(value) > 253 or '.' not in value or
            not all(re.fullmatch(r'[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?', p)
                    for p in value.split('.'))):
        raise ValueError('Use a lowercase DNS domain, e.g. rocento.com')
    return value


