def delivery_geocoding_nginx(existing, domain):
    """Public coordinate lookup; no customer cookies/credentials reach the provider."""
    validate_domain(domain)
    marker = '# BEGIN Rocento delivery geocoding'
    if marker in existing:
        return existing
    shared = """# BEGIN Rocento delivery geocoding
map $host $delivery_geocode_key { default "delivery-geocode"; }
map $arg_lang $delivery_geocode_language { default ""; en "&lang=en"; }
limit_req_zone $delivery_geocode_key zone=delivery_geocode_client:1m rate=1r/s;
proxy_cache_path /var/cache/nginx/delivery-geocode levels=1:2 keys_zone=delivery_geocode:2m max_size=32m inactive=24h;
# END Rocento delivery geocoding
"""
    location = """    location = /api/v1/location-address {
        if ($request_method != GET) { return 405; }
        if ($arg_lat !~ "^-?[0-9]{1,2}([.][0-9]{1,6})?$") { return 400; }
        if ($arg_lon !~ "^-?[0-9]{1,3}([.][0-9]{1,6})?$") { return 400; }
        if ($arg_lang !~ "^(en|ar)$") { return 400; }
        limit_req zone=delivery_geocode_client burst=2;
        limit_req_status 429;
        access_log off;
        proxy_pass_request_headers off;
        proxy_pass_request_body off;
        proxy_set_header Content-Length "";
        proxy_set_header Host photon.komoot.io;
        proxy_set_header User-Agent "RocentoDelivery/1.0 (+https://rocento.com)";
        proxy_ssl_server_name on;
        proxy_ssl_name photon.komoot.io;
        proxy_ssl_verify on;
        proxy_ssl_verify_depth 3;
        proxy_ssl_trusted_certificate /etc/ssl/certs/ca-certificates.crt;
        resolver 1.1.1.1 1.0.0.1 valid=300s;
        set $delivery_geocoder https://photon.komoot.io;
        proxy_pass $delivery_geocoder/reverse?lat=$arg_lat&lon=$arg_lon&limit=1&radius=0.2$delivery_geocode_language;
        proxy_connect_timeout 5s;
        proxy_read_timeout 10s;
        proxy_cache delivery_geocode;
        proxy_cache_key "$arg_lat:$arg_lon:$arg_lang";
        proxy_cache_lock on;
        proxy_cache_valid 200 24h;
        add_header Cache-Control "private, max-age=300" always;
        add_header X-Content-Type-Options nosniff always;
    }
"""
    for host in ('grocery', 'jewelry', 'electronics', 'pharmacy', 'apps'):
        target = f'    server_name {host}.{domain};\n'
        if existing.count(target) != 1:
            raise ValueError(f'Expected one {host} server; no configuration changed')
        existing = existing.replace(target, target + location)
    return shared + existing

