def storefront_private_docs_block():
    return '''    # Merchant reference is available only on the administration host.
    location = /api/v1/admin/api-reference/openapi.json { return 404; }
    location ^~ /api/v1/admin/api-reference/ { return 404; }
'''


def secure_merchant_api_docs_nginx(existing, domain):
    """Add viewer headers without publishing a private spec as a static asset."""
    validate_domain(domain)
    viewer, blocked = merchant_api_docs_locations(), storefront_private_docs_block()
    if existing.count(viewer) in (3, 4) and existing.count(blocked) == existing.count(viewer):
        return existing
    if ('BEGIN Rocento merchant API documentation' in existing or
            'location = /api-reference' in existing or
            'location ^~ /api/v1/admin/api-reference/' in existing):
        raise ValueError('Existing merchant documentation policy differs; review Nginx manually.')
    folders = ['grocery-admin', 'jewelry-admin', 'electronics-admin']
    if 'current/pharmacy-admin;' in existing:
        folders.append('pharmacy-admin')
    for folder in folders:
        root = f'    root /var/www/rocento/current/{folder};\n'
        if existing.count(root) != 1:
            raise ValueError('Expected three managed admin roots; no configuration changed.')
        existing = existing.replace(root, root + viewer)
    root = '    root /var/www/rocento/current/storefront;\n'
    if existing.count(root) != len(folders):
        raise ValueError('Expected three or four managed storefront roots; no configuration changed.')
    return existing.replace(root, root + blocked)


