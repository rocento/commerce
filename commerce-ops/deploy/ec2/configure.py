def prepare_assistant(directory):
    """Give each store its own signing identity and AI-only credentials."""
    for store in ('grocery', 'jewelry', 'electronics', 'pharmacy'):
        env_path = directory / f'{store}-assistant.env'
        secret_dir = directory.resolve() / 'assistant' / store
        if not env_path.exists():
            if secret_dir.exists() and any(secret_dir.iterdir()):
                raise ValueError(f'Restore {env_path}; assistant secrets already exist')
            fd = os.open(env_path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
            with os.fdopen(fd, 'w') as stream:
                stream.write(f'ASSISTANT_TENANT_ID={uuid4()}\nASSISTANT_SECRETS_DIR={secret_dir}\n')
        env_path.chmod(0o600)
        secret_dir.mkdir(parents=True, exist_ok=True)
        secret_dir.parent.chmod(0o700)
        secret_dir.chmod(0o700)
        private, public = secret_dir / 'private.pem', secret_dir / 'public.pem'
        if not private.exists():
            if public.exists():
                raise ValueError(f'Restore {private}; the existing public key must be preserved')
            subprocess.run(['openssl', 'genpkey', '-algorithm', 'RSA', '-pkeyopt',
                            'rsa_keygen_bits:3072', '-out', str(private)],
                           check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        if not public.exists():
            subprocess.run(['openssl', 'pkey', '-in', str(private), '-pubout', '-out', str(public)],
                           check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        # Private parent directories protect host access; dedicated read-only
        # mounts let the non-root gateway and AI database read their own keys.
        for path in (private, public):
            path.chmod(0o644)
        for name in ('store-admin-password', 'store-runtime-password'):
            path = secret_dir / name
            if not path.exists():
                fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o644)
                with os.fdopen(fd, 'w') as stream:
                    stream.write(secrets.token_urlsafe(48))
            path.chmod(0o644)


def demo_catalog(store, domain):
    """Advertise real browsing instructions, without claiming an MCP/A2A server."""
    validate_domain(domain)
    if store not in ('grocery', 'jewelry', 'electronics', 'pharmacy'):
        raise ValueError('Unknown demo store')
    name = f'Rocento {store.title()} Demo'
    return {
        'specVersion': '1.0',
        'host': {'displayName': name},
        'entries': [{
            'identifier': f'urn:air:{store}.{domain}:skills:shopping',
            'displayName': f'{name} Shopping Skills',
            'type': 'text/markdown; profile="urn:air:agent-skills"',
            'url': f'https://{store}.{domain}/.well-known/agent-skills.md',
            'description': f'Instructions for browsing and comparing products in the {store} demo storefront.',
            'capabilities': ['BrowseProducts', 'CompareProducts'],
            'representativeQueries': [
                f'Browse products in the Rocento {store} demo',
                f'Compare available {store} products and prices',
            ],
        }],
    }


