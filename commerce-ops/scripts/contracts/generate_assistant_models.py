"""Generate strict Python DTOs from the same OpenAPI used by React and Rust tests."""
import json
from pathlib import Path
root = Path(__file__).resolve().parents[3]
schemas = json.loads((root / 'commerce-api/rocento-api/openapi.json').read_text())['components']['schemas']
lines = ['# Generated by commerce-ops/scripts/contracts/generate_assistant_models.py; do not edit.', 'from __future__ import annotations', '', 'from datetime import datetime', 'from typing import Literal', 'from uuid import UUID', '', 'from pydantic import BaseModel, ConfigDict, Field', '', '']
def typ(s):
    if not s:
        t = 'object'
    elif '$ref' in s:
        t = s['$ref'].split('/')[-1]
    elif 'anyOf' in s:
        t = ' | '.join(typ(part) for part in s['anyOf'])
    elif 'enum' in s:
        values = [v for v in s['enum'] if v is not None]
        t = 'Literal[' + ', '.join(repr(v) for v in values) + ']' if values else 'None'
    elif s['type'] == 'array':
        t = 'list[' + typ(s['items']) + ']'
    else:
        t = {'string':'str','integer':'int','boolean':'bool','number':'float'}[s['type']]
        t = {'uuid':'UUID','date-time':'datetime'}.get(s.get('format'), t)
    return t + ' | None' if s.get('nullable') and t != 'None' else t
for name, s in schemas.items():
    if not name.startswith('Assistant'):
        continue
    lines += [f'class {name}(BaseModel):', '    model_config = ConfigDict(extra="forbid")']
    for name, v in s['properties'].items():
        t = typ(v)
        optional = name not in s['required']
        if optional and 'None' not in t: t += ' | None'
        bounds = [f'{b}={v[a]!r}' for a,b in [('maxLength','max_length'),('minLength','min_length'),('maxItems','max_length'),('minimum','ge'),('maximum','le'),('minItems','min_length'),('pattern','pattern')] if a in v]
        if optional: bounds.insert(0, 'default=None')
        if name == 'entity_id' and v.get('readOnly'):
            bounds.append('strict=True')
            if optional: bounds.append('exclude_if=lambda value: value is None')
        lines.append(f'    {name}: {t}' + (' = Field(' + ', '.join(bounds) + ')' if bounds else ''))
    lines += ['', '']
lines += [f'{name}.model_rebuild()' for name in schemas if name.startswith('Assistant')]
target = root / 'commerce-assistant-platform/app/commerce_action_engine/contracts/__init__.py'
target.parent.mkdir(parents=True, exist_ok=True)
target.write_text('\n'.join(lines) + '\n')
