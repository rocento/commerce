"""Generate the Node/Python resolution contract from the Python ingress model.

Run with commerce-assistant-platform/.venv/bin/python. --check is read-only and fails on drift.
"""

import argparse
import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / "commerce-assistant-platform"))

from app.commerce_action_engine.execution.language.gate import ResolutionEnvelope


def ts_type(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    if "anyOf" in schema:
        return " | ".join(ts_type(value) for value in schema["anyOf"])
    kind = schema.get("type")
    if kind == "array":
        return f"Array<{ts_type(schema.get('items', {}))}>"
    if kind == "object":
        if "properties" not in schema:
            extra = schema.get("additionalProperties", {})
            return f"Record<string, {ts_type(extra) if isinstance(extra, dict) else 'unknown'}>"
        required = schema.get("required", [])
        members = [
            f"  {json.dumps(key)}{'' if key in required else '?'}: {ts_type(value)};"
            for key, value in schema["properties"].items()
        ]
        return "{\n" + "\n".join(members) + "\n}"
    return {
        "string": "string",
        "integer": "number",
        "number": "number",
        "boolean": "boolean",
        "null": "null",
    }.get(kind, "unknown")


def outputs() -> dict[Path, str]:
    schema = ResolutionEnvelope.model_json_schema(by_alias=True)
    schema["$schema"] = "https://json-schema.org/draft/2020-12/schema"
    schema["$id"] = "urn:commerce-ai:language-resolution:v2"
    encoded = json.dumps(schema, indent=2) + "\n"
    types = "// Generated by commerce-ops/scripts/contracts/generate_language_resolution_contract.py. Do not edit.\n"
    types += "\n\n".join(
        f"export type {name} = {ts_type(value)};"
        for name, value in schema.get("$defs", {}).items()
    )
    types += f"\n\nexport type ResolutionEnvelope = {ts_type(schema)};\n"
    generated = ROOT / "commerce-assistant-platform/app/commerce_language_engine/src/generated"
    return {
        ROOT / "commerce-assistant-platform/contracts/language-resolution/v2/schema.json": encoded,
        generated / "language-resolution.schema.json": encoded,
        generated / "language-resolution-types.ts": types,
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for path, content in outputs().items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if stale:
        raise SystemExit("Generated language contract is stale: " + ", ".join(stale))


if __name__ == "__main__":
    main()
