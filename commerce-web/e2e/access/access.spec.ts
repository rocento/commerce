import { test, expect } from '@playwright/test';
const actor = '10000000-0000-0000-0000-000000000001';
const entity = '20000000-0000-0000-0000-000000000002';
test.beforeEach(async ({ page }) => {
  await page.route('**/api/v1/**', async route => {
    const url = new URL(route.request().url());
    let body: unknown = {};
    if (url.pathname.endsWith('/admin/me')) body = { user: { id: actor, name: 'Test Admin', email: 'test@example.com' }, permissions: ['*'] };
    else if (url.pathname.endsWith('/sorts')) body = url.pathname.includes('audit') ? ['id', 'created_at'] : ['id', 'name'];
    else if (url.pathname.endsWith('/exports/columns/audit')) body = { columns: ['id', 'action', 'actor_id', 'entity_id', 'created_at', 'details'] };
    else if (url.pathname.endsWith('/exports')) body = [];
    else if (url.pathname.endsWith('/grids/audit')) body = { items: [{ id: entity, actor_id: actor, actor_name: 'Test Admin', actor_email: 'test@example.com', entity_id: entity, entity_name: 'Catalog team', entity_type: 'Role', action: 'admin.role_updated', created_at: '2026-10-01T12:00:00Z', details: { before: { permissions: [] }, after: { permissions: ['catalog.read'] } } }], total_count: 1, next_cursor: null };
    else if (url.pathname.endsWith('/grids/roles')) body = { items: [{ id: entity, name: 'Catalog team', permissions: ['catalog.read'], system: false }], total_count: 1, next_cursor: null };
    await route.fulfill({ json: body });
  });
});
test('audit filters execute on the server and show full evidence', async ({ page }) => {
  const initial = page.waitForRequest(r => r.url().includes('/grids/audit?'));
  await page.goto('/system/audit');
  const url = new URL((await initial).url());
  expect(url.searchParams.get('sort')).toBe('created_at');
  expect(url.searchParams.get('descending')).toBe('true');
  const actorLabel = page.getByRole('button', { name: 'Test Admin test@example.com' });
  const entityLabel = page.getByRole('button', { name: 'Catalog team Role' });
  await expect(actorLabel).toBeVisible();
  await expect(entityLabel).toBeVisible();
  const actorFiltered = page.waitForRequest(r => r.url().includes('/grids/audit?') && new URL(r.url()).searchParams.get('actor_id') === actor);
  await actorLabel.click();
  await actorFiltered;
  const entityFiltered = page.waitForRequest(r => r.url().includes('/grids/audit?') && new URL(r.url()).searchParams.get('entity_id') === entity);
  await entityLabel.click();
  await entityFiltered;
  await page.locator('.audit-filter-panel > summary').click();
  await page.getByLabel('Action', { exact: true }).fill('admin.role_updated');
  await page.getByLabel('From (local time, inclusive)').fill('2026-10-01T00:00');
  await page.getByLabel('Until (local time, exclusive)').fill('2026-10-02T00:00');
  const filtered = page.waitForRequest(r => r.url().includes('/grids/audit?') && r.url().includes('created_from'));
  await page.getByRole('button', { name: 'Apply filters' }).click();
  expect(new URL((await filtered).url()).searchParams.get('action')).toBe('admin.role_updated');
  await page.getByText('View event', { exact: true }).click();
  await expect(page.locator('.audit-evidence')).toContainText('catalog.read');
  await expect(page.locator('.audit-evidence')).toContainText(actor);
  await expect(page.locator('.audit-evidence')).toContainText(entity);
  await page.getByLabel('Show UTC').check();
  await expect(page.locator('time')).toContainText('UTC');
  await page.screenshot({ path: '/tmp/admin-audit-enterprise.png', fullPage: true });
  await page.getByRole('button', { name: 'Export results' }).click();
  const exported = page.waitForRequest(r => r.url().endsWith('/exports') && r.method() === 'POST');
  await page.getByRole('button', { name: 'Start background export' }).click();
  expect((await exported).postDataJSON().request).toMatchObject({ action: 'admin.role_updated', sort: 'created_at', descending: true });
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
});
test('role edits require review before writing and show grants', async ({ page }) => {
  let writes = 0;
  await page.route('**/api/v1/admin/roles', async route => { writes++; expect(route.request().postDataJSON().permissions).toContain('catalog.read'); await route.fulfill({ json: {} }); });
  await page.goto('/system/roles');
  await page.getByRole('button', { name: 'Add role' }).click();
  await page.getByLabel('Role name', { exact: true }).fill('Catalog reviewers');
  await page.getByRole('checkbox', { name: 'View catalog', exact: true }).check();
  await page.getByRole('button', { name: 'Review changes' }).click();
  expect(writes).toBe(0);
  await expect(page.getByRole('heading', { name: 'Grant · 1' })).toBeVisible();
  await page.screenshot({ path: '/tmp/admin-role-review.png', fullPage: true });
  await page.getByRole('button', { name: 'Confirm and save role' }).click();
  await expect(page.getByRole('status').filter({ hasText: 'Role saved' })).toBeVisible();
  expect(writes).toBe(1);
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.getByRole('heading', { name: 'Catalog team' })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: '/tmp/admin-roles-mobile.png', fullPage: true });
});

test('read-only users can inspect roles without mutation controls', async ({ page }) => {
  await page.route('**/api/v1/admin/me', route => route.fulfill({ json: { user: { id: actor, name: 'Reviewer', email: 'reviewer@example.com' }, permissions: ['iam.roles.read'] } }));
  await page.goto('/system/roles');
  await expect(page.getByRole('heading', { name: 'Catalog team' })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Add role' })).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Actions' })).toHaveCount(0);
  await page.getByText('Inspect permissions', { exact: true }).click();
  await expect(page.getByText('View catalog', { exact: true })).toBeVisible();
});
