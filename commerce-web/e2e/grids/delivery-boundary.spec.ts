import { test, expect } from '@playwright/test';
test('draw, undo, edit and save a custom delivery boundary', async ({ page }) => {
  const id='11111111-1111-4111-8111-111111111111';
  let saved: Record<string, unknown> | undefined;
  await page.route('**/api/**',route=>route.fulfill({json:[]}));
  await page.route('**/api/v1/admin/me',route=>route.fulfill({json:{user:{id,name:'Test Admin',email:'admin@example.test'},permissions:['*']}}));
  await page.route('**/api/v1/admin/grids/*/sorts',route=>route.fulfill({json:['id','name']}));
  await page.route('**/api/v1/admin/grids/delivery-areas?*',route=>route.fulfill({json:{items:saved?[{...saved,id}]:[],next_cursor:null}}));
  await page.route('**/api/v1/admin/inventory/stocks',route=>route.fulfill({json:[{id,name:'Test stock'}]}));
  await page.route('**/api/v1/admin/inventory/delivery-areas',route=>{
    if(route.request().method()==='GET')return route.fulfill({json:saved?[{...saved,id}]:[]});
    saved=route.request().postDataJSON();return route.fulfill({json:{id}});
  });
  await page.goto('/catalog/delivery-areas');
  await page.getByRole('button',{name:'New delivery area',exact:true}).click();
  await page.getByLabel('Delivery area name',{exact:true}).fill('Custom neighborhood');
  const save=page.getByRole('button',{name:'Create delivery area',exact:true});
  await expect(save).toBeDisabled();
  await expect(page.getByLabel('Radius (km)',{exact:true})).toHaveCount(0);
  const map=page.getByLabel('Delivery boundary map. Click to add points; drag numbered points to adjust.',{exact:true});
  for(const position of [{x:140,y:100},{x:350,y:100},{x:350,y:270}])await map.click({position});
  await expect(page.getByText('3 / 100 points',{exact:false})).toBeVisible();
  await page.getByLabel('Test stock',{exact:true}).check();
  await expect(save).toBeEnabled();
  await page.getByRole('button',{name:'Undo last point'}).click();
  await expect(save).toBeDisabled();
  await map.click({position:{x:150,y:270}});
  await page.getByText('Edit boundary coordinates',{exact:true}).click();
  await page.getByLabel('Point 1 latitude',{exact:true}).fill('30.05');
  await page.getByLabel('Test stock',{exact:true}).check();
  await save.click();
  await expect.poll(()=>saved?.boundary).toBeTruthy();
  expect(saved).not.toHaveProperty('radius_km');
  expect(saved).not.toHaveProperty('center_lat');
  expect(saved?.boundary).toHaveLength(3);
  expect((saved?.boundary as {latitude:number}[])[0].latitude).toBe(30.05);
  await page.getByRole('button',{name:'Clear boundary'}).click();
  await expect(page.getByRole('button',{name:'Save delivery area',exact:true})).toBeDisabled();
  page.once('dialog',dialog=>dialog.accept());
  await page.getByRole('button',{name:'Close editor',exact:true}).click();
  await page.getByRole('button',{name:'Actions for Custom neighborhood',exact:true}).click();
  await page.getByRole('menuitem',{name:'Edit',exact:true}).click();
  await expect(page.getByText('3 / 100 points',{exact:false})).toBeVisible();
});
