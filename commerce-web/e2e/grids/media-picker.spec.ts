import { test, expect } from '@playwright/test';
const category = { id: '11111111-1111-4111-8111-111111111111', name: 'Egyptian Breakfast', slug: 'egyptian-breakfast', parent_id: null };
const media = [{ id: '22222222-2222-4222-8222-222222222222', alt: 'Breakfast banner' }, { id: '33333333-3333-4333-8333-333333333333', alt: 'Fresh bread' }];
test('visual selection, search, cancel, remove and independent saving', async ({ page }, info) => {
  await page.route('**/api/**', route => route.fulfill({ json: [] }));
  await page.route('**/api/v1/admin/languages', route => route.fulfill({ json: { source_locale: 'en', languages: [], publication_available: true } }));
  await page.route('**/api/v1/admin/markets', route => route.fulfill({ json: { items: [], live: { region: 'EG', currency: 'EGP' }, locales: ['en'], activation_available: false } }));
  await page.route('**/api/v1/admin/me', route => route.fulfill({ json: { user: { id: category.id, name: 'Test Admin', email: 'admin@example.test' }, permissions: ['*'] } }));
  await page.route('**/api/v1/admin/catalog/categories', route => route.fulfill({ json: [category] }));
  await page.route('**/api/v1/admin/attribute-definitions?*', route => route.fulfill({ json: ['banner', 'thumbnail'].map(code => ({ attribute_code: code, label: code === 'banner' ? 'Banner' : 'Thumbnail', input_type: 'media_image', is_required: false, options: [] })) }));
  await page.route('**/api/v1/admin/catalog/media', route => route.fulfill({ json: media }));
  await page.route('**/api/v1/catalog/media/*/content', route => route.fulfill({ contentType: 'image/svg+xml', body: '<svg xmlns="http://www.w3.org/2000/svg" width="300" height="180"><rect width="300" height="180" fill="#f3dfba"/><ellipse cx="150" cy="90" rx="95" ry="45" fill="#b77332"/></svg>' }));
  let values: Record<string, string> = { banner: media[0].id };
  await page.route(`**/api/v1/admin/catalog/categories/${category.id}/attributes`, route => { if (route.request().method() === 'PUT') values = route.request().postDataJSON(); return route.fulfill({ json: values }); });
  await page.goto(`/catalog/categories/${category.id}`);
  const banner = page.getByRole('group', { name: 'Banner', exact: true });
  const thumbnail = page.getByRole('group', { name: 'Thumbnail', exact: true });
  await expect(banner.getByRole('img')).toHaveAttribute('src', `/api/v1/catalog/media/${media[0].id}/content`);
  await thumbnail.getByRole('button', { name: 'Choose thumbnail image' }).click();
  const dialog = page.getByRole('dialog');
  await expect(dialog.getByRole('img')).toHaveCount(2);
  await dialog.getByRole('searchbox').fill('missing');
  await expect(dialog).toContainText('No images match your search.');
  await dialog.getByRole('searchbox').fill('Fresh');
  await expect(dialog.getByRole('img')).toHaveCount(1);
  await dialog.getByRole('button', { name: 'Select Fresh bread' }).click();
  await expect(dialog).toHaveCount(0);
  await expect(thumbnail.getByRole('img')).toHaveAttribute('src', `/api/v1/catalog/media/${media[1].id}/content`);
  await expect(banner.getByRole('img')).toHaveAttribute('src', `/api/v1/catalog/media/${media[0].id}/content`);
  await page.getByRole('button', { name: 'Save category attributes', exact: true }).click();
  await expect.poll(() => values).toEqual({ banner: media[0].id, thumbnail: media[1].id });
  await banner.getByRole('button', { name: 'Choose banner image' }).click();
  await expect(dialog.getByRole('button', { name: 'Select Breakfast banner' })).toHaveAttribute('aria-pressed', 'true');
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await dialog.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true);
  await page.screenshot({ path: info.outputPath('media-picker-mobile.png') });
  await page.keyboard.press('Escape');
  await expect(dialog).toHaveCount(0);
  await expect(banner.getByRole('button', { name: 'Choose banner image' })).toBeFocused();
  await thumbnail.getByRole('button', { name: 'Remove thumbnail image' }).click();
  await page.getByRole('button', { name: 'Save category attributes', exact: true }).click();
  await expect.poll(() => values).toEqual({ banner: media[0].id });
});
