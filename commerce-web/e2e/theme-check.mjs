import { chromium } from '@playwright/test';
import { mkdir, readFile } from 'node:fs/promises';
const browser = await chromium.launch({ headless: true });
await mkdir('test-results/theme', { recursive: true });
try {
  const context = await browser.newContext({ storageState: 'test-results/.auth/admin.json', viewport: { width: 1440, height: 1000 } });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  const credentials = await readFile('../.local/admin-credentials.txt', 'utf8');
  const email = credentials.match(/^Email: (.+)$/m)?.[1];
  const password = credentials.match(/^Password: (.+)$/m)?.[1];
  const login = await context.request.post('http://127.0.0.1:5178/api/v1/admin/auth/login', { headers: { 'X-Commerce-Request': '1' }, data: { email, password } });
  if (!login.ok()) throw new Error(`Local admin login failed: ${login.status()}`);
  await page.goto('http://127.0.0.1:5178/content/themes');
  await page.getByRole('heading', { name: 'Themes', exact: true }).waitFor();
  await page.getByLabel('Theme name', { exact: true }).fill(`Theme verification ${Date.now()}`);
  await page.getByRole('button', { name: 'Create theme', exact: true }).click();
  await page.getByRole('button', { name: 'Back to themes', exact: true }).waitFor();
  await page.locator('summary').filter({ hasText: 'Hero' }).click();
  await page.locator('details[open]').getByLabel('heading', { exact: true }).fill('A fresh perspective');
  await page.getByRole('button', { name: 'Save draft', exact: true }).click();
  await page.getByText('Draft saved.', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Validate', exact: true }).click();
  await page.getByText('Theme validation passed.', { exact: true }).waitFor();
  await page.screenshot({ path: 'test-results/theme/admin-desktop.png', fullPage: true });
  await page.getByRole('button', { name: 'Publish', exact: true }).click();
  await page.getByRole('button', { name: 'Confirm publication' }).click();
  await page.getByText('New version published.', { exact: true }).waitFor();
  await page.getByRole('tab', { name: 'History', exact: true }).click();
  await page.getByText('V1 · Live', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Rollback', exact: true }).click();
  await page.getByRole('button', { name: 'Confirm publication' }).click();
  await page.getByText('V2 · Live', { exact: true }).waitFor();
  await page.getByRole('tab', { name: 'Preview', exact: true }).click();
  await page.frameLocator('iframe').getByRole('heading', { name: 'A fresh perspective' }).waitFor();
  await page.frameLocator('iframe').getByText('Draft preview', { exact: true }).waitFor();
  await page.getByRole('tab', { name: 'History', exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'test-results/theme/admin-mobile.png', fullPage: true });
  const adminOverflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth);
  await page.goto('http://127.0.0.1:5177/');
  await page.getByRole('heading', { name: 'Good food. Everyday.' }).waitFor();
  await page.locator('.theme-hero img').evaluate(img => img.decode());
  await page.screenshot({ path: 'test-results/theme/storefront-mobile.png', fullPage: true });
  const mobileOverflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth);
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.screenshot({ path: 'test-results/theme/storefront-desktop.png', fullPage: true });
  const desktopOverflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth);
  console.log(JSON.stringify({ errors, adminOverflow, mobileOverflow, desktopOverflow }));
  if (errors.length || adminOverflow || mobileOverflow || desktopOverflow) process.exitCode = 1;
} finally { await browser.close(); }
