import { chromium, expect } from '@playwright/test';
import { execFileSync } from 'node:child_process';
import { readFileSync, mkdirSync, writeFileSync } from 'node:fs';
const origin = process.env.PREVIEW_ORIGIN || 'http://127.0.0.1:5194';
const fixture = JSON.parse(readFileSync(process.env.PREVIEW_FIXTURE_STATE || '/tmp/rocento-android-preview/fixture.json', 'utf8'));
const output = process.env.PREVIEW_EVIDENCE_DIR || '/tmp/rocento-android-preview/evidence';
mkdirSync(output, { recursive: true });
const browser = await chromium.launch({ headless: true });
try {
  const context = await browser.newContext({ viewport: { width: 1600, height: 1100 } });
  await context.addCookies([{ name: 'admin_session', value: fixture.adminCookie, url: origin }]);
  const page = await context.newPage();
  await page.goto(origin);
  await page.getByRole('combobox', { name: /^Preview (app|platform)$/ }).selectOption('android');
  const started = page.waitForResponse(r => r.url().includes('/sessions/worker') && r.request().method() === 'POST');
  await page.getByRole('button', { name: 'Open Android Preview', exact: true }).click();
  expect((await started).status()).toBe(200);
  const canvas = page.getByRole('application', { name: 'Interactive Android preview' });
  await expect(canvas).toHaveAttribute('data-live', 'true', { timeout: 180000 });
  await canvas.screenshot({ path: `${output}/android-native.png` });
  await expect(page.locator('.ms-native-session')).toContainText('Up to date', { timeout: 90000 });
  const before = Number(await canvas.getAttribute('data-frames'));
  const time = Date.now(); await page.waitForTimeout(5000);
  const fps = (Number(await canvas.getAttribute('data-frames')) - before) / ((Date.now() - time) / 1000);
  expect(fps).toBeGreaterThan(1);
  await page.getByRole('button', { name: 'Sections', exact: true }).click();
  const text = `Android live draft updated — native Compose preview ${Date.now()}`;
  const saved = page.waitForResponse(r => r.request().method() === 'PUT' && r.url().includes('/app-config/draft'));
  await page.getByRole('textbox', { name: 'English content', exact: true }).fill(text);
  const savedResponse = await saved;
  expect(savedResponse.status()).toBe(200);
  const revision = (await savedResponse.json()).revision;
  await expect(page.locator('.ms-native-session')).toContainText(`Native applied draft r${revision} · Up to date`, { timeout: 30000 });
  await page.waitForTimeout(3000);
  await canvas.screenshot({ path: `${output}/android-draft-updated.png` });
  const adbPath = process.env.ANDROID_ADB || `${process.env.HOME}/Library/Android/sdk/platform-tools/adb`;
  const adb = (...args) => execFileSync(adbPath, ['-P', '5038', '-s', 'emulator-5580', ...args], { encoding: 'utf8', timeout: 20000 });
  const tree = () => { adb('shell', 'uiautomator', 'dump', '/data/local/tmp/preview-tree.xml'); return adb('exec-out', 'cat', '/data/local/tmp/preview-tree.xml'); };
  expect(tree()).toContain(text);
  await canvas.scrollIntoViewIfNeeded();
  const input = page.waitForResponse(r => r.url().endsWith('/input') && r.request().method() === 'POST');
  const box = await canvas.boundingBox();
  await canvas.click({ position: { x: box.width * .5, y: box.height * .11 } });
  expect((await input).status()).toBe(204);
  await page.keyboard.type('milk', { delay: 200 });
  await expect.poll(() => tree(), { timeout: 15000 }).toContain('text="milk"');
  await canvas.screenshot({ path: `${output}/android-keyboard.png` });
  const scroll = page.waitForResponse(r => r.url().endsWith('/input') && r.request().postDataJSON()?.kind === 'swipe');
  await canvas.hover(); await page.mouse.wheel(0, 300);
  expect((await scroll).status()).toBe(204);
  await context.setOffline(true);
  await expect(canvas).toHaveAttribute('data-live', 'false', { timeout: 10000 });
  await context.setOffline(false);
  await expect(canvas).toHaveAttribute('data-live', 'true', { timeout: 20000 });
  await expect(page.locator('.ms-native-stream')).toContainText('Live Android video', { timeout: 10000 });
  await page.screenshot({ path: `${output}/builder-android.png`, fullPage: true });
  await page.getByRole('button', { name: 'Stop native preview', exact: true }).click();
  await expect(canvas).toHaveCount(0);
  writeFileSync(`${output}/result.json`, JSON.stringify({ platform: 'android', fps, draftAck: true, tap: true, keyboard: true, nativeTextVerified: true, revision, swipe: true, reconnect: true, stopped: true }, null, 2));
  console.log(JSON.stringify({ fps, status: 'passed', output }));
} finally { await browser.close(); }
