import { chromium, expect } from '@playwright/test';
import { readFile, mkdir } from 'node:fs/promises';
const browser = await chromium.launch({headless:true});
const out = 'test-results/theme-layout';
await mkdir(out,{recursive:true});
const creds = await readFile('../.local/admin-credentials.txt','utf8');
const context = await browser.newContext({viewport:{width:1440,height:1000}});
const errors=[];
try {
 const auth = await context.request.post('http://localhost:5174/api/v1/admin/auth/login',{headers:{'X-Commerce-Request':'1'},data:{email:creds.match(/^Email: (.+)$/m)[1],password:creds.match(/^Password: (.+)$/m)[1]}});
 expect(auth.status()).toBe(200);
 const page = await context.newPage(); page.on('pageerror', e=>errors.push(e.message));
 await page.goto('http://localhost:5174/content/themes');
 await page.getByLabel('Theme name',{exact:true}).fill(`Layout QA ${Date.now()}`);
 await page.getByRole('button',{name:'Create theme',exact:true}).click();
 await page.getByRole('button',{name:'Category',exact:true}).click();
 await page.getByRole('button',{name:/Horizontal filters/}).click();
 await expect(page.getByRole('button',{name:/Horizontal filters/})).toHaveAttribute('aria-pressed','true');
 await page.screenshot({path:`${out}/category-desktop.png`,fullPage:true});
 await page.getByRole('button',{name:'Search',exact:true}).click();
 await page.getByRole('button',{name:/Vertical filters/}).click();
 await page.getByRole('button',{name:'Global header',exact:true}).click();
 await page.getByLabel(/sticky/i).selectOption('on');
 await page.getByRole('button',{name:'Global footer',exact:true}).click();
 await page.getByLabel(/^service 1$/i).fill('Made for everyday moments');
 await page.getByLabel(/^column 1 heading$/i).fill('Customer care');
 await page.getByRole('button',{name:'Save draft',exact:true}).click();
 await expect(page.getByText('Draft saved.',{exact:true})).toBeVisible();
 await expect(page.getByRole('button',{name:'Save draft',exact:true})).toBeDisabled();
 await expect(page.getByRole('button',{name:'Publish',exact:true})).toBeEnabled();
 await page.screenshot({path:`${out}/footer-settings-desktop.png`,fullPage:true});
 await page.getByRole('tab',{name:'Preview',exact:true}).click();
 const frame=page.frameLocator('iframe');
 await expect(frame.locator('.footer-services')).toContainText('Made for everyday moments');
 await expect(frame.locator('.theme-header')).toHaveAttribute('data-sticky','on');
 const src=await page.locator('iframe').getAttribute('src');
 const id=new URL(src).searchParams.get('theme_preview');
 const saved=await (await context.request.get(`http://localhost:5174/api/v1/admin/themes/${id}`)).json();
 expect(saved.configuration.pages.category.find(s=>s.component==='catalog_filters').settings.layout).toBe('horizontal');
 expect(saved.configuration.pages.search.find(s=>s.component==='catalog_filters').settings.layout).toBe('vertical');
 await page.getByLabel('Preview size').selectOption('mobile');
 await expect(page.locator('iframe')).toHaveCSS('width','390px');
 await page.setViewportSize({width:390,height:844});
 await page.getByRole('tab',{name:'Sections',exact:true}).click();
 await page.getByRole('button',{name:'Category',exact:true}).click();
 await page.screenshot({path:`${out}/category-mobile.png`,fullPage:true});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)).toBe(false);
 const shop=await context.newPage(); shop.on('pageerror',e=>errors.push(e.message));
 const catalog=await (await context.request.get('http://localhost:5173/api/v1/catalog/categories')).json();
 const categories=Array.isArray(catalog)?catalog:catalog.items||[];
 if(!categories[0]?.id) throw new Error('No category fixture');
 await shop.goto(`http://localhost:5173/categories/${categories[0].id}?theme_preview=${id}`);
 await expect(shop.locator('.catalog-layout')).toHaveAttribute('data-filter-layout','horizontal');
 await shop.goto(`http://localhost:5173/search?theme_preview=${id}`);
 await expect(shop.locator('.catalog-layout')).toHaveAttribute('data-filter-layout','vertical');
 await shop.goto('http://localhost:5273/');
 await shop.locator('.store-shell[data-presentation=heritage]').waitFor();
 await shop.locator('.theme-footer-core').screenshot({path:`${out}/jewelry-footer-desktop.png`});
 await shop.setViewportSize({width:390,height:844});
 await shop.locator('.theme-footer-core').screenshot({path:`${out}/jewelry-footer-mobile.png`});
 expect(await shop.evaluate(()=>document.documentElement.scrollWidth>innerWidth)).toBe(false);
 expect(errors).toEqual([]);
 console.log(JSON.stringify({status:'passed',draft:id,screenshots:out,errors}));
} catch (error) {
 for (const [i, page] of context.pages().entries()) await page.screenshot({path:`${out}/failure-${i}.png`,fullPage:true}).catch(()=>{});
 throw error;
} finally {await browser.close();}
