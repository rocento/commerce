// Invoked by the opt-in Rust integration test; API calls go to its real Postgres-backed router.
import { chromium, expect } from '@playwright/test';
import { readFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
let input = '';
for await (const chunk of process.stdin) input += chunk;
const fixture = JSON.parse(input);
if (![fixture.origin, fixture.backend].every(url => new URL(url).hostname === '127.0.0.1')) throw new Error('Only isolated loopback fixtures are supported');
const output = fileURLToPath(new URL('../../../.local/customer-journey/', import.meta.url));
await mkdir(output, {recursive: true});
const browser = await chromium.launch({headless: true});
try {
  const context = await browser.newContext({viewport: {width: 1440, height: 1000}, acceptDownloads: true});
  await context.addCookies([{name: 'admin_session', value: 'journey-admin', url: fixture.origin, httpOnly: true, sameSite: 'Strict'}]);
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  // Forward, never replace, actual API responses from the test gateway.
  await page.route('**/api/**', async route => {
    const url = new URL(route.request().url());
    const response = await route.fetch({url: fixture.backend + url.pathname.replace(/^\/api/, '') + url.search});
    await route.fulfill({response});
  });
  await page.goto(`${fixture.origin}/customers/profiles/${fixture.customers[0]}`);
  await expect(page.getByRole('heading', {name: 'Customer 0', exact: true}).first()).toBeVisible();
  await page.getByRole('link', {name: 'See journey'}).click();
  await expect(page).toHaveURL(new RegExp(`/customers/journey/${fixture.customers[0]}$`));
  await expect(page.getByRole('region', {name: 'Selected customer'})).toContainText('Customer 0');
  await expect(page.getByRole('heading', {name: 'Order placed', exact: true})).toBeVisible();
  await expect(page.getByRole('heading', {name: 'Product viewed', exact: true})).toBeVisible();
  await expect(page.getByRole('heading', {name: 'Checkout quoted', exact: true})).toBeVisible();
  await expect(page.getByText('Olivia Bennett')).toHaveCount(0);
  await expect(page.getByText(/Visa ending/)).toHaveCount(0);
  const search = page.locator('.cj-event').filter({has: page.getByRole('heading', {name: 'Products searched'})});
  await expect(search).toContainText('0 results');
  await search.getByRole('button', {name: 'Event details'}).click();
  await expect(page.getByRole('dialog')).toContainText(fixture.customers[0]);
  await page.keyboard.press('Escape');
  await expect(page.getByRole('dialog')).not.toBeVisible();
  const download = page.waitForEvent('download');
  await page.getByRole('button', {name: 'Export displayed events'}).click();
  const saved = await download;
  const exported = JSON.parse(await readFile(await saved.path(), 'utf8'));
  expect(exported.customer.id).toBe(fixture.customers[0]);
  expect(exported.events.find(event => event.kind === 'purchase').details.order_id).toBe(fixture.order_id);
  expect(exported.events).toHaveLength(7);
  await page.reload();
  await expect(page.getByRole('heading', {name: 'Order placed', exact: true})).toBeVisible();
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({path: output + 'journey-desktop.png', fullPage: true});
  await page.locator('.cj-journey').screenshot({path: output + 'journey-desktop-flow.png', style: '.admin-header { visibility: hidden; }'});
  await page.getByLabel('From (UTC)').fill('2020-01-01');
  await page.getByLabel('To (UTC)').fill('2020-01-02');
  await page.getByRole('button', {name: 'Apply dates'}).click();
  await expect(page.getByRole('heading', {name: 'No activity recorded in this range'})).toBeVisible();
  await page.goto(`${fixture.origin}/customers/journey/${fixture.customers[1]}`);
  await expect(page.getByRole('region', {name: 'Selected customer'})).toContainText('Customer 1');
  await expect(page.getByRole('heading', {name: 'No activity recorded in this range'})).toBeVisible();
  await expect(page.getByRole('heading', {name: 'Order placed', exact: true})).toHaveCount(0);
  await page.route(`**/customers/${fixture.customers[0]}/journey?*`, route => route.abort('connectionreset'), {times: 1});
  await page.goto(`${fixture.origin}/customers/journey/${fixture.customers[0]}`);
  await expect(page.getByRole('button', {name: 'Retry activity'})).toBeVisible();
  await page.getByRole('button', {name: 'Retry activity'}).click();
  await expect(page.getByRole('heading', {name: 'Order placed', exact: true})).toBeVisible();
  await page.setViewportSize({width: 900, height: 900});
  await page.locator('.cj-journey').screenshot({path: output + 'journey-tablet-flow.png', style: '.admin-header { visibility: hidden; }'});
  await page.setViewportSize({width: 390, height: 844});
  await page.evaluate(() => window.scrollTo(0, 0));
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({path: output + 'journey-mobile.png', fullPage: true});
  await page.locator('.cj-journey').screenshot({path: output + 'journey-mobile-flow.png', style: '.admin-header { visibility: hidden; }'});
  await page.setViewportSize({width: 320, height: 740});
  await page.locator('.cj-journey').screenshot({path: output + 'journey-small-mobile-flow.png', style: '.admin-header { visibility: hidden; }'});
  await page.goto(`${fixture.origin}/customers/journey`);
  await expect(page.getByRole('link', {name: 'Choose a customer'})).toBeVisible();
  expect(errors).toEqual([]);
  console.log('PASS: profile → real customer journey, order identity, refresh, event details, JSON export, date filtering, customer isolation, empty states, connection retry and mobile layout');
} finally { await browser.close(); }
