// Compile the canonical schema ahead of time: browsers must not need unsafe-eval.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";
import Ajv2020 from "ajv/dist/2020.js";
import standalone from "ajv/dist/standalone/index.js";
const require = createRequire(import.meta.url);
const { buildSync } = createRequire(require.resolve("vite"))("esbuild");
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const schema = JSON.parse(fs.readFileSync(path.join(root, "src/mobile-contract.json"), "utf8"));
const ajv = new Ajv2020({ allErrors: true, strict: false, code: { source: true } });
const validate = ajv.compile(schema);
const result = buildSync({
  stdin: { contents: standalone(ajv, validate), resolveDir: root, sourcefile: "mobile-validator.cjs" },
  bundle: true,
  format: "esm",
  platform: "browser",
  target: "es2022",
  minify: true,
  write: false,
});
const output = "// Generated by scripts/generate-mobile-validator.mjs; do not edit.\n" + result.outputFiles[0].text;
const target = path.join(root, "src/mobile-validator.generated.js");
if (process.argv.includes("--check")) {
  if (!fs.existsSync(target) || fs.readFileSync(target, "utf8") !== output) {
    console.error("Mobile validator is stale. Run node packages/api-client/scripts/generate-mobile-validator.mjs from frontend.");
    process.exit(1);
  }
  console.log("Mobile schema validator is current and precompiled.");
} else {
  fs.writeFileSync(target, output);
  console.log("Generated CSP-compatible mobile schema validator.");
}
